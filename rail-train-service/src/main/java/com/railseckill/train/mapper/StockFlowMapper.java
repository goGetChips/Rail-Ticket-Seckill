/*
 * =============================================================================
 *  【流水表为什么天生就没有"改"和"删"】
 * =============================================================================
 *   这不是"阶段 5 还没做"，而是**流水表这个设计本身的性质**：
 *
 *     流水是"已经发生过的事"的记录。改一条流水，等于篡改历史。
 *     如果某次扣减需要撤销，正确的做法是**追加一条 change_type=3（回补）
 *     的负数流水**，而不是把原来那条删掉或改成没发生过。
 *
 *   这也是为什么 change_count 的符号约定是"扣减为正、回补为负"：
 *   有了它，"某一行库存的净变化"就能直接 SUM 出来，
 *   而每一条流水都**永远保留着当时的真相**。
 *
 *   对账任务（阶段 9）依赖的正是这一点：能被核对的是一个只增不改的
 *   日志，而不是一张会被就地修改的表。
 *
 * -----------------------------------------------------------------------------
 *  ⚠️ 它也是跨库写的第二张表
 * -----------------------------------------------------------------------------
 *   biz_id 里存的是 rail_order 那边的 order_no，而表住在 rail_inventory 库。
 *   没有外键（全项目不建外键），所以"这条流水的订单真的存在吗"
 *   数据库层面不保证 —— 靠 sql/99_verify.sql 里那条 LEFT JOIN 校验来查。
 *   完整说明见 entity/StockFlow.java。
 * =============================================================================
 */
