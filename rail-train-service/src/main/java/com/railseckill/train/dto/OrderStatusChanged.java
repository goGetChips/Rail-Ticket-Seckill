package com.railseckill.train.dto;

/**
 * 支付（状态流转）成功的响应体。
 *
 * <p>用于 {@code POST /api/order/orders/{orderNo}/pay} 的 200 响应。
 *
 * @param orderNo    业务订单号
 * @param status     流转后的状态：1=已支付
 * @param statusLabel 状态的中文名
 * @param idempotent <b>本次调用是否只是重复确认</b>：
 *                   {@code false} = 这次真的把订单从待支付改成了已支付；
 *                   {@code true}  = 订单本来就是已支付，本次没有改变任何东西
 */
/*
 * =============================================================================
 *  ⭐⭐ 【idempotent 这个字段是"让幂等可见"】
 * =============================================================================
 *   两次支付同一个订单都会返回 200（这是幂等：重复请求不产生额外副作用），
 *   但从响应上看不出区别 —— 调用方无法回答"我这次到底改没改状态"。
 *
 *   这在排查问题时是有代价的：日志里两条一模一样的成功响应，
 *   你分不清哪条是"真的支付了"、哪条是"重复确认"。
 *   尤其是支付这种涉及钱的路径，"哪一次是真的"必须可回答。
 *
 *   加一个布尔字段就能回答它，成本是一个字段。
 *
 *   ⚠️ 命名用 `idempotent` 而不是更短的 `duplicate`：
 *       "duplicate" 听起来像错误（重复提交是坏的），
 *       而这里**重复本身是正常且被欢迎的**（网络重试就会产生重复）。
 *       用一个听起来像错的词描述正确行为，会让读日志的人误判。
 *
 * -----------------------------------------------------------------------------
 *  ⚠️ 【为什么没有"支付时间"字段】
 * -----------------------------------------------------------------------------
 *   因为 t_order 表里没有这一列 —— 只有 update_time。
 *   要加"支付时间"需要改表结构，而阶段 5 的范围是模拟支付，
 *   不为一个没有对账需求的字段做 DDL。
 *   （真实的支付系统必须有支付时间 + 支付流水号，那是阶段 7 的事，
 *   而且那时应该改 docs/06-database.md 里的表设计，不是顺手塞进响应体。）
 *
 *   ★ 这个"缺席"值得留意：**它是本阶段知道、但故意不补的一个缺口**，
 *     而不是没想清楚。区别在于它被记录下来了。
 * =============================================================================
 */
public record OrderStatusChanged(
        String orderNo,
        Integer status,
        String statusLabel,
        boolean idempotent) {
}
