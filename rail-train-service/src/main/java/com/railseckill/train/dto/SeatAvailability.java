package com.railseckill.train.dto;

import java.math.BigDecimal;

/**
 * 某个车次 / 某一天 / 某个席别的余票。
 *
 * <p>用于 {@code GET /api/inventory/seats?trainNo=G1&date=2026-09-30}。
 *
 * @param seatType   1=商务座 2=一等座 3=二等座
 * @param price      票价
 * @param totalCount 总票额
 * @param soldCount  已售数量
 * @param remaining  余票 = totalCount - soldCount
 */
/*
 * =============================================================================
 *  【为什么要有这个 DTO，不直接返回 SeatInventory 实体】
 * =============================================================================
 *   实体是表的镜像，直接返回会把这几样东西一起暴露出去：
 *
 *     id           库存行的自增主键。对调用方毫无意义，且一旦暴露，
 *                  就有人会拿它去查东西 —— 而它是会随重跑种子脚本变化的
 *     trainId      内部 id。调用方手里有 trainNo（G1），不需要 trainId
 *     createTime   / updateTime   内部审计字段
 *
 *   更要紧的是**方向**：实体描述"数据库里有什么"，
 *   DTO 描述"这个接口承诺什么"。两者的演进节奏不同 ——
 *   表加了一列审计字段，不应该自动变成接口的破坏性变更。
 *
 * =============================================================================
 *  ⭐ 【remaining 为什么在 Java 里算，而不写进 SQL 的 SELECT】
 * =============================================================================
 *   两种写法都行：SQL 里写 `total_count - sold_count AS remaining`，
 *   或者在 Service 里映射时算。这里选后者，原因是：
 *
 *   1. **余票的算法会有第二处输入。** 阶段 5 之后，"可售"很可能不再等于
 *      total - sold，还要减去"已锁定但未支付"的数量。
 *      到时候这个算法要在**一处**改。写在 SQL 里的话，那个 SQL 属于
 *      InventoryMapper，而锁定数可能在另一张表 —— 改动会散开。
 *      放在 Service 的映射方法里，它天然就是"库存实体 → 对外余票"的唯一转换点。
 *
 *   2. **它是阶段 8 迁移的天然切口。** 这个映射方法所在的 Service
 *      将来要整体搬到 rail-inventory-service。
 *      逻辑集中在 Java 里比散在 SQL 里更容易一起搬走。
 *
 *   【为什么不用 Math.max(0, remaining) 兜底】
 *   表上有 CHECK 约束 `sold_count <= total_count`，remaining 不可能为负。
 *   加 max(0, ...) 会把"约束被绕过"或"数据被手工改坏"这两种
 *   **本该报警的情况**悄悄压成 0，让问题延后到更难查的地方爆发。
 *   已经有的保证不要再用代码重复一遍 —— 那是把两处正确性混在一起，
 *   出错时无法判断是哪一层失效了。
 *
 * =============================================================================
 *  【soldCount 该不该返回给用户】
 * =============================================================================
 *   真实售票系统一般不把"已售数量"给到前端（属于经营数据）。
 *   本项目返回它，是因为这是一个**教学项目**：
 *   面试时能指着响应说"remaining 就是 total 减 sold，两个数都在这"，
 *   比只看到一个 remaining 更有说服力 —— 数据是可自证的。
 *
 *   ⚠️ 如果这是真实项目，这里应该只返回 seatType / price / remaining。
 *   **这个取舍要能说出来，而不是默认"多返回点信息没坏处"。**
 * =============================================================================
 */
public record SeatAvailability(
        Integer seatType,
        BigDecimal price,
        Integer totalCount,
        Integer soldCount,
        Integer remaining) {
}
