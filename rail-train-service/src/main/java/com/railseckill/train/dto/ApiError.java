package com.railseckill.train.dto;

import java.util.List;

/**
 * 错误响应体。
 *
 * <p>由 {@code exception/ApiExceptionHandler} 统一生成。
 *
 * @param status  HTTP 状态码，同时也是响应体的状态码（冗余，但让响应体自解释）
 * @param error   HTTP 原因短语，如 {@code "Bad Request"}
 * @param message 面向人的一句话说明
 * @param details 逐字段的失败原因；没有细分时为空列表（**不是 null**）
 */
/*
 * =============================================================================
 *  ⭐ 【为什么这不算"引入了统一响应体包装"】
 * =============================================================================
 *   本项目刻意**没有**采用 `{code: 0, msg: "ok", data: {...}}` 那种包装，
 *   理由见 controller/StationController 里的说明。这里的 ApiError 不违背它，
 *   因为两者的作用面完全不同：
 *
 *     统一响应体包装     →  改变**成功**响应的形状
 *     ApiError          →  只改变**失败**响应的形状
 *
 *   成功时仍然是"HTTP 200 + 原始数据"，一点没变。
 *   失败时返回一个结构化的错误体，而不是 Spring Boot 默认那坨
 *   `{"timestamp":..., "status":400, "error":"Bad Request", "path":"..."}`
 *   —— 默认体里没有 `message`（默认被关掉）也没有字段级明细，
 *   调用方只能看到一个 400，不知道为什么。
 *
 * =============================================================================
 *  【status 字段和 HTTP 状态码重复，为什么还留着】
 * =============================================================================
 *   冗余，但是有用的冗余：把响应体存进日志或消息队列之后，
 *   HTTP 状态码就丢了，那时响应体里还能看出这是哪一类错误。
 *   代价是两处可能不一致 —— 所以生成它的代码只有一处
 *   （ApiExceptionHandler），不允许别处手写这个对象。
 *
 * =============================================================================
 *  ⚠️ 【details 为什么不能为 null】
 * =============================================================================
 *   构造时一律传 List.of() 而不是 null。理由和 StationController 里
 *   "查不到返回空数组而不是 null"是同一条：
 *   JSON 里 `"details": null` 会让前端写 `details.map(...)` 时直接抛异常，
 *   而 `"details": []` 天然安全。**集合类型的"没有"应该用空集合表达。**
 *
 * =============================================================================
 *  【这里没有错误码枚举，这是刻意的】
 * =============================================================================
 *   没有 code 字段，也没有一个 ErrorCode 枚举。
 *   原因见 docs/api/error-codes.md：错误码规范应该从**真实发生过的**
 *   错误场景里长出来，而不是先编一张表再往上套。
 *   阶段 4 只产生了 400 / 404 两类业务错误，
 *   现在就为它们发明一套编号，将来一定会被推翻重来。
 * =============================================================================
 */
public record ApiError(
        int status,
        String error,
        String message,
        List<String> details) {
}
