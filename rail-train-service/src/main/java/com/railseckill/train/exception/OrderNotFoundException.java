package com.railseckill.train.exception;

import org.springframework.http.HttpStatus;

import java.util.List;

/**
 * 订单不存在。
 *
 * <p>对应 HTTP <b>404 Not Found</b>。
 */
/*
 * =============================================================================
 *  ⭐ 【为什么业务异常里需要一个 404 的类】
 * =============================================================================
 *   两个理由，第二个更重要。
 *
 *   【理由一：语义上它确实存在】
 *   支付一个不存在的订单号（用户手输错了、或者订单号是上一轮测试的），
 *   这是**完全正常**的调用错误，不是服务端问题。
 *   判据还是那一句：**404 = "你指的东西不存在"；409 = "东西存在但规则不允许"。**
 *   订单号查不到 → 404。订单在但已取消 → 409。
 *   如果这里返回 409，前端会把"订单号打错了"显示成"这个订单不能支付"，
 *   用户永远找不到自己打错字这件事。
 *
 *   【理由二：它让 BusinessException.status 这个字段是真的字段】
 *   如果所有子类都是 409，那 status 就是一个伪装成字段的常量，
 *   抽象基类上的这个字段就成了多余的抽象。
 *   有了 404 的成员，"状态码由异常自己携带"这个设计才真正被用到 ——
 *   ★ 一个只有一个取值的抽象，是没被验证过的抽象。
 *
 * -----------------------------------------------------------------------------
 *  【和 Controller 里那些 ResponseEntity.notFound() 的区别】
 * -----------------------------------------------------------------------------
 *   阶段 4 的查询接口用的是 `ResponseEntity.notFound().build()`（返回空 body），
 *   那是**因为那些接口没有 body 可给**。
 *
 *   而这里必须给 body：调用方需要一个结构化的错误体来知道
 *   "是哪个订单号没找到"。返回空 body 会让"订单不存在"和"路径写错了"
 *   看起来一模一样（都是 404 + 空）。详见 docs/api/error-codes.md §五。
 * =============================================================================
 */
public class OrderNotFoundException extends BusinessException {

    public OrderNotFoundException(String orderNo) {
        super(HttpStatus.NOT_FOUND, "订单不存在", List.of("orderNo=" + orderNo));
    }
}
