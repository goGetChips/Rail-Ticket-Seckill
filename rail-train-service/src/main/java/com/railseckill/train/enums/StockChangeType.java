package com.railseckill.train.enums;

/**
 * 库存变动类型，对应 {@code t_stock_flow.change_type}。
 *
 * <p>取值约定见 {@code sql/03_rail_inventory.sql}：1=预扣 2=确认扣减 3=回补。
 */
/*
 * =============================================================================
 *  ⭐ 三个取值里，阶段 5 只写 CONFIRM —— 这张表说清了"为什么"
 * =============================================================================
 *
 *   取值空间是为**方案 C（Redis 预扣 + MQ 异步落库）**设计的：
 *
 *     | 值 | 名字        | 含义                                   | 谁写它     |
 *     |----|-------------|----------------------------------------|------------|
 *     | 1  | PRE_DEDUCT  | 预扣：Redis 里扣了，数据库还没落         | 阶段 7     |
 *     | 2  | CONFIRM     | 确认扣减：数据库里的 sold_count 真的 +1  | **阶段 5** |
 *     | 3  | RELEASE     | 回补：订单取消/超时，把票还回去          | 阶段 7     |
 *
 *   【阶段 5 为什么只写 CONFIRM，不写 PRE_DEDUCT】
 *   方案 A 没有两阶段。扣减这一下就是**终局** ——
 *   `UPDATE ... SET sold_count = sold_count + 1` 执行成功，
 *   这张票就真的卖出去了，后面支付只改订单状态、**不再碰库存**。
 *   没有"先预扣、稍后确认"这个中间态，所以 PRE_DEDUCT 无处可用。
 *
 *   强行为阶段 5 造一个 PRE_DEDUCT/CONFIRM 两阶段是错的：
 *   它会给一张票造出两条流水，而这两条流水在方案 A 里
 *   永远是同一个事务里连着写的，没人能从中获得任何信息。
 *
 *   【阶段 5 也不写 RELEASE】
 *   回补的前提是"有取消或超时关单"，而阶段 5 这两个都没有
 *   （范围是下单 + 模拟支付，见 OrderStatus 的类注释）。
 *   没有回补路径，`sold_count` 只增不减。
 *
 * -----------------------------------------------------------------------------
 *  【既然 1 和 3 用不到，为什么还定义它们】
 * -----------------------------------------------------------------------------
 *   因为 `sql/04_rail_order.sql` 的"禁止裸写数字"这条规则
 *   对 change_type 同样成立，而**部分枚举是最坏的一种**：
 *
 *   如果这里只放 CONFIRM(2)，下一个要写回补的人在编译器的帮助下
 *   找不到 RELEASE，他要么去翻 DDL 注释手写一个 `3`，要么
 *   临时在某个类里加一个常量 —— 两条路都会让"取值约定"散成两处。
 *
 *   而一个枚举**只要它完整镜像了 DDL 的取值空间**，就是一份权威的对照表。
 *   上面那张表就是它的价值：读代码的人不用去翻 SQL 脚本。
 *
 *   ⚠️ 代价（诚实写出来）：PRE_DEDUCT 和 RELEASE 目前**没有被任何代码引用**。
 *   这不是"为将来预留"的接口（那种东西本项目的立场是反对的），
 *   区别在于：枚举常量是**对既有取值空间的命名**，
 *   而"预留一个空的 handler / 空的方法"是**对不存在的行为建模**。
 *   前者不会误导人以为某个功能已经实现，后者会。
 * =============================================================================
 */
public enum StockChangeType {

    /** 预扣：Redis 里扣了、数据库还没落。阶段 7 引入 Redis 后使用。 */
    PRE_DEDUCT(1, "预扣"),

    /** 确认扣减：数据库里的 sold_count 真的 +1。**阶段 5 唯一会写入的值。** */
    CONFIRM(2, "确认扣减"),

    /** 回补：订单取消或超时，把票还回去。阶段 7 引入取消/超时关单后使用。 */
    RELEASE(3, "回补");

    private final int code;

    private final String label;

    StockChangeType(int code, String label) {
        this.code = code;
        this.label = label;
    }

    /** 数据库里存的值。 */
    public int code() {
        return code;
    }

    /** 中文名，用于拼日志。 */
    public String label() {
        return label;
    }

    /**
     * 由数据库值反查枚举。
     *
     * <p>无法识别时抛异常，理由同 {@link SeatType#of(int)}。
     */
    public static StockChangeType of(int code) {
        for (StockChangeType type : values()) {
            if (type.code == code) {
                return type;
            }
        }
        throw new IllegalArgumentException("未知的库存变动类型：" + code + "（约定只有 1/2/3）");
    }
}
